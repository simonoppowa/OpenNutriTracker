/// after Backend#10 changed the order the search RPCs answer in. No row is
/// edited: "Orange juice, 100%,  freshly squeezed" and "Potato, boiled, from
/// fresh,  peel eaten, no added fat" carry the backend's double spaces.
///
/// The English ones are `search_food_summary(term, null, 100)` as it
/// answered — the call `SpFoodDataSource._searchEnglish` makes
/// (`_candidatePoolSize`) — in the function's order, which is now
/// `food_has_deliverable_portion(food_id) desc, title = term desc,
/// length(name), food_id`: the rows with a portion first, among them the
/// rows titled exactly as the query, shortest first. The hundred are still
/// the backend's own cut, made before any client code runs, but where the
/// old order — portion, then id — filled the hundred for `potato` with
/// beef stews and left the whole "Potato" family at ranks 128 to 488, the
/// new one leads with "Potato, NFS" and holds a hundred rows titled
/// "Potato". The German ones are `search_food_translation(term, 'de',
/// 100)` as it answered, in the same order over the translated
/// description.
///
/// Beside each row, the number of portions `portions_by_food_ids(ids,
/// loc)` delivers for it — `gram_weight > 0`, after the RPC's own filter
/// — which is the count `MealEntity.portions` holds once
/// `ProductsRepository` has decorated a fresh page, and what the
/// resolver's no-portions penalty and portions key read. Every row the
/// backend orders as having a portion has at least one here, and every
/// row it orders as having none has none.
///
/// What each pool holds, as fetched (rows / with a portion / titled as the
/// term / titled and with a portion):
///
/// * `potato`: 100 / 100 / 100 / 100
/// * `bread`: 100 / 100 / 100 / 100
/// * `chicken breast`: 98 / 30 / 38 / 29
/// * `egg`: 100 / 100 / 27 / 27
/// * `eggs`: 100 / 100 / 0 / 0
/// * `milk`: 100 / 100 / 20 / 20
/// * `apple`: 100 / 20 / 4 / 4
/// * `orange juice`: 45 / 9 / 20 / 7
/// * `rice`: 100 / 100 / 100 / 100
/// * `carrots`: 100 / 100 / 22 / 22
/// * `muffins`: 79 / 40 / 20 / 0
/// * `Milch` (de): 100 / 85 / 32 / —
/// * `Kartoffel` (de): 100 / 62 / 52 / —
///
/// `eggs` is here beside `egg` because the backend answers the two
/// differently: the full-text match stems `eggs` to `egg` and finds the
/// same family, but no title equals `eggs`, so the title-first key does
/// nothing and the hundred are the shortest matches of any title.
///
/// `muffins` is here for the one thing the data source's cut does not
/// read, the portions: the full-text match finds the survey's "Muffin"
/// family, forty rows with a portion, and behind them the twenty SR
/// Legacy rows that spell their title "Muffins" — none with a portion,
