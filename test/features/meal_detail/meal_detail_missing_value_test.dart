// #1474: a food missing a required value (BLS "Apfel getrocknet" had no
// fat) disabled Add, yet the screen showed "0.0 g" fat as if it were known.
// A missing value shows as missing, a real 0 as 0, and the warning names
// what is missing.

MealEntity _driedApple({double? energyKcal100 = 242, double? fat100}) =>
    MealEntity(
      code: 'missing-value-test',
      name: 'Apfel getrocknet',
      url: null,
      mealQuantity: null,
      mealUnit: 'g',
      servingQuantity: null,
      servingUnit: 'g',
      servingSize: null,
      nutriments: MealNutrimentsEntity(
        energyKcal100: energyKcal100,
        carbohydrates100: 53.4,
        fat100: fat100,
        proteins100: 1.3,
        sugars100: 50,
        saturatedFat100: 0.1,
        fiber100: 10.7,
      ),
      source: MealSourceEntity.custom,
    );

void main() {
  final getIt = GetIt.instance;

  setUp(() {
    getIt.registerLazySingleton<MealDetailBloc>(
      () => MealDetailBloc(
        _FakeAddIntakeUsecase(),
        _FakeAddTrackedDayUsecase(),
        _FakeGetKcalGoalUsecase(),
        _FakeGetMacroGoalUsecase(),
        _FakeGetTrackedDayUsecase(),
        _FakeProductsRepository(),
        _FakeRemoteSearchCacheDataSource(),
      ),
    );
    getIt.registerLazySingleton<GetConfigUsecase>(_FakeGetConfigUsecase.new);
    getIt.registerLazySingleton<GetIntakeUsecase>(_FakeGetIntakeUsecase.new);
    getIt.registerLazySingleton<CacheManager>(_FakeCacheManager.new);
    final favourites = FakeFavourites();
    getIt.registerFactory<FavouriteToggleBloc>(
      () => FavouriteToggleBloc(favourites.get, favourites.toggle),
    );
    getIt.registerLazySingleton<HomeBloc>(_FakeHomeBloc.new);
    getIt.registerLazySingleton<DiaryBloc>(_FakeDiaryBloc.new);
    getIt.registerLazySingleton<CalendarDayBloc>(_FakeCalendarDayBloc.new);
  });

  tearDown(() async {
    await getIt.reset();
  });

  Future<void> pumpMealDetail(WidgetTester tester, MealEntity meal) async {
    tester.view.physicalSize = const Size(1080, 2400);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.reset);

    Route<void> routeFor(RouteSettings settings) => MaterialPageRoute<void>(
      settings: settings,
      builder: (_) => const MealDetailScreen(),
    );

    await tester.pumpWidget(
      ChangeNotifierProvider<EnergyUnitProvider>(
        create: (_) => EnergyUnitProvider(),
        child: MaterialApp(
          localizationsDelegates: const [S.delegate],
          supportedLocales: S.supportedLocales,
          initialRoute: NavigationOptions.mealDetailRoute,
          onGenerateInitialRoutes: (_) => [
            routeFor(
              RouteSettings(
                name: NavigationOptions.mealDetailRoute,
                arguments: MealDetailScreenArguments(
                  meal,
                  IntakeTypeEntity.breakfast,
                  DateTime(2026, 10, 25),
                  false,
                ),
              ),
            ),
          ],
          onGenerateRoute: routeFor,
        ),
      ),
    );
    await tester.pumpAndSettle();
  }

  Finder inSummary(String label, Finder matching) => find.descendant(
    of: find.widgetWithText(MealDetailMacroNutrients, label),
    matching: matching,
  );

  Finder inTable(Finder matching) =>
      find.descendant(of: find.byType(Table), matching: matching);

  testWidgets('a missing fat value shows as missing and is named', (
    tester,
  ) async {
    await pumpMealDetail(tester, _driedApple(fat100: null));

    expect(
      inSummary(l10nEn.fatLabel, find.text(missingNutrientPlaceholder)),
      findsOneWidget,
    );
    expect(inTable(find.text(missingNutrientPlaceholder)), findsOneWidget);
    expect(find.textContaining('0.0 g'), findsNothing);
    expect(inTable(find.text('0.0g')), findsNothing);

    expect(find.textContaining(l10nEn.missingProductInfo), findsOneWidget);
    expect(
      find.textContaining(l10nEn.missingProductInfoFields(l10nEn.fatLabel)),
      findsOneWidget,
    );
  });

  testWidgets('a real 0 g fat shows as 0, with no warning', (tester) async {
    await pumpMealDetail(tester, _driedApple(fat100: 0));

    expect(inSummary(l10nEn.fatLabel, find.text('0.0 g')), findsOneWidget);
    expect(inTable(find.text('0.0g')), findsOneWidget);
    expect(find.text(missingNutrientPlaceholder), findsNothing);

    expect(find.textContaining(l10nEn.missingProductInfo), findsNothing);
  });

  testWidgets('missing energy and fat show as missing and are both named', (
    tester,
  ) async {
    await pumpMealDetail(
      tester,
      _driedApple(energyKcal100: null, fat100: null),
    );

    // The summary's kcal, its fat, and the table's energy and fat rows.
    expect(find.text(missingNutrientPlaceholder), findsNWidgets(4));
    expect(inTable(find.text(missingNutrientPlaceholder)), findsNWidgets(2));
    expect(
      find.textContaining(
        l10nEn.missingProductInfoFields(
          '${l10nEn.energyLabel}, ${l10nEn.fatLabel}',
        ),
      ),
      findsOneWidget,
    );
  });
}

